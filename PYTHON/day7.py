# -----------------------------------
# CREATE LIST 
# -----------------------------------
students = ["Prince", "Priya", "Khushi"]

print("\nOriginal List: ")
print(students)

# -----------------------------------
# INDEXING 
# -----------------------------------
print("\nFirst student:")
print(students[0])

print("\nLast student:")
print(students[-1])

# -----------------------------------
# SLICING 
# -----------------------------------
print("\nFirst Two Students:")
print(students[:2])

print("\nLast Two Students:")
print(students[1:])

# -----------------------------------
# APPEND 
# -----------------------------------
students.append("Isha")

print("\nAfter append():")
print(students)

# -----------------------------------
# INSERT 
# -----------------------------------
students.insert(1,"Wick")

print("\nAfter insert():")
print(students)

# -----------------------------------
# REMOVE 
# -----------------------------------
students.remove("Isha")


print("\nAfter remove():")
print(students)

# -----------------------------------
# POP
# -----------------------------------
students.pop

print("\nAfter pop():")
print(students)

# -----------------------------------
# FINAL LIST 
# -----------------------------------
print("\nFinal List:")
print(students)

